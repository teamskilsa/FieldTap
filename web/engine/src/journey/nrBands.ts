/** The bands used in Canada (MCC 302), the United States (310-316) and Mexico (334). 873.85 MHz is n5, n18 and n26
 *  on paper, but n18 is a Japanese band. */
const NORTH_AMERICA = new Set([2, 5, 7, 12, 13, 14, 25, 26, 29, 30, 38, 41, 46, 48, 53, 66, 70, 71, 77, 85, 90, 96, 102, 104, 105, 258, 260, 261, 262]);

const isNorthAmerican = (mcc: number) => mcc === 302 || (mcc >= 310 && mcc <= 316) || mcc === 334;

/**
 * NR bands whose DL range holds `arfcn`, narrowed by region for MCC 302, 310-316 and 334. Test PLMNs (001, 999)
 * and every other MCC are not narrowed, and overlapping bands are all listed (CONTRACT.md v1 amendments).
 */
export function nrBandCandidates(arfcn: number, mcc: number | null): number[] {
  const all = BANDS.filter(([, first, last]) => arfcn >= first && arfcn <= last).map(([b]) => b);
  if (mcc === null || !isNorthAmerican(mcc)) return all;
  const narrowed = all.filter((b) => NORTH_AMERICA.has(b));
  return narrowed.length ? narrowed : all;
}
